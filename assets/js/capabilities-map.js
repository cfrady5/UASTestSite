/* =====================================================================
   Midwest UAS Test Site of Indiana — interactive capabilities map
   ---------------------------------------------------------------------
   Turns the static capability list on /capabilities into a two-column
   explorer: a capability navigation on the left, a layered SVG map of the
   Indiana testing network on the right, and a detail panel below the nav.

   Progressive enhancement
   -----------------------
   The page ships the ten capabilities as an ordinary <ol>, and the IEDC
   network map inside <noscript>. Everything below runs only if this file
   loads; if it does not, the page is the list and the map image it was
   before, with nothing hidden behind a control that never initialised.

   Geometry
   --------
   assets/js/map-data.js is generated by tools/build_map.py from Census
   cartographic boundaries, Natural Earth and OurAirports, all projected
   through one Albers equal-area conic. Nothing here estimates a
   coordinate, and nothing here draws a testing boundary: range and
   corridor geometry render only from verified data in site_data.py,
   which is empty until the test site publishes it.

   State
   -----
   One store, two keys — the selected capability and the selected
   facility. Every visual difference between states is a class on the
   root element or on a marker, applied by one apply() pass. There is no
   per-capability animation code: the data drives which ids light up.
   ===================================================================== */
(function () {
  'use strict';

  var root = document.querySelector('[data-cap-explorer]');
  var MAP = window.UAS_MAP;
  if (!root || !MAP) return;

  var SVGNS = 'http://www.w3.org/2000/svg';
  var reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  var uid = 0;
  function nextId(prefix) { uid += 1; return prefix + '-' + uid; }

  function el(tag, attrs, kids) {
    var node = document.createElement(tag);
    fill(node, attrs, kids);
    return node;
  }

  function svg(tag, attrs, kids) {
    var node = document.createElementNS(SVGNS, tag);
    fill(node, attrs, kids);
    return node;
  }

  function fill(node, attrs, kids) {
    Object.keys(attrs || {}).forEach(function (k) {
      if (attrs[k] === null || attrs[k] === undefined) return;
      if (k === 'text') node.textContent = attrs[k];
      else if (k === 'html') node.innerHTML = attrs[k];
      else node.setAttribute(k, attrs[k]);
    });
    (kids || []).forEach(function (c) { if (c) node.appendChild(c); });
  }

  /* ---------------------------------------------------------------
     Store
     --------------------------------------------------------------- */
  var state = { capability: null, facility: null };
  var listeners = [];

  function set(patch) {
    var changed = false;
    Object.keys(patch).forEach(function (k) {
      if (state[k] !== patch[k]) { state[k] = patch[k]; changed = true; }
    });
    if (changed) listeners.forEach(function (fn) { fn(state); });
  }

  var byId = {};
  MAP.capabilities.forEach(function (c) { byId[c.id] = c; });

  var facilityById = {};
  MAP.facilities.forEach(function (f) { facilityById[f.id] = f; });

  var NETWORK_IDS = MAP.facilities
    .filter(function (f) { return f.network; })
    .map(function (f) { return f.id; });

  var NETWORK_COUNTY_IDS = (MAP.networkCounties || [])
    .map(function (c) { return c.id; });

  /* Which sites a capability lights up, and on what footing.
     'confirmed' — the capability names these sites itself.
     'pending'   — no assignment has been supplied, so the whole testing
                   network is shown and the panel says it is unassigned.
     'service'   — no geography at all; see site_data.py. */
  function resolve(capability) {
    if (!capability) return { basis: 'none', sites: [], counties: [] };
    if (capability.kind === 'service') {
      return { basis: 'service', sites: [], counties: [] };
    }
    var sites = capability.sites || [];
    var counties = capability.counties || [];
    if (sites.length || counties.length) {
      return { basis: 'confirmed', sites: sites, counties: counties };
    }
    return { basis: 'pending', sites: NETWORK_IDS, counties: NETWORK_COUNTY_IDS };
  }

  /* Capabilities that name a given facility. Empty for every facility
     today — see resolve() above. */
  function capabilitiesAt(facilityId) {
    return MAP.capabilities.filter(function (c) {
      return (c.sites || []).indexOf(facilityId) !== -1;
    });
  }

  /* ---------------------------------------------------------------
     Marker symbols
     ---------------------------------------------------------------
     Drawn as geometry rather than emoji or pictorial pins: this is an
     operational chart, and the glyphs are the ones the IEDC network map
     uses — a crosshair for installations, a plane for airports, an
     anchor for ports. Each is defined once and referenced with <use>. */
  /* The symbols are drawn at roughly 12 units across; the map renders about
     1000 units into 520–760 CSS px, so they need scaling up to stay legible
     as marks rather than specks. One constant, applied to every glyph. */
  var GLYPH = 1.9;

  var SYMBOLS = {
    city:       '<circle r="3.4"/>',
    capital:    '<path d="M0 -6.2 1.6 -2 6.2 -2 2.5 0.9 3.9 5.3 0 2.6 -3.9 5.3 -2.5 0.9 -6.2 -2 -1.6 -2Z"/>',
    airport:    '<path d="M0 -6 1.1 -2.2 6 0.6 6 2 1.1 0.9 1.1 4 2.9 5.3 2.9 6.2 0 5.5 -2.9 6.2 -2.9 5.3 -1.1 4 -1.1 0.9 -6 2 -6 0.6 -1.1 -2.2Z"/>',
    port:       '<path d="M0 -6a1.7 1.7 0 1 1 0 3.4 1.7 1.7 0 0 1 0-3.4Zm-.9 3.9h1.8v6.3h-1.8ZM-4 -2.1h8v1.7h-8Z"/>'
                + '<path d="M-5.4 1.2a5.4 5.4 0 0 0 10.8 0" fill="none" stroke-width="1.7"/>',
    military:   '<circle r="5.2" fill="none" stroke-width="1.6"/>'
                + '<path d="M0 -7v3.4M0 3.6V7M-7 0h3.4M3.6 0H7" stroke-width="1.6" fill="none"/>'
                + '<circle r="1.7"/>',
    agency:     '<circle r="5.4" fill="none" stroke-width="1.6"/><circle r="2.4"/>',
    university: '<path d="M0 -5.6 7 -2.1 0 1.4 -7 -2.1Z"/>'
                + '<path d="M-4.2 -0.6V3.2c0 1.8 8.4 1.8 8.4 0V-0.6" fill="none" stroke-width="1.5"/>'
  };

  function symbolFor(f) {
    return f.capital ? 'capital' : f.type;
  }

  /* ---------------------------------------------------------------
     Map
     --------------------------------------------------------------- */
  function buildMap() {
    var clipId = nextId('uas-clip');
    var titleId = nextId('uas-map-title');
    var descId = nextId('uas-map-desc');

    var node = svg('svg', {
      'class': 'uasmap',
      viewBox: MAP.viewBox.join(' '),
      role: 'group',
      'aria-labelledby': titleId + ' ' + descId
    });

    node.appendChild(svg('title', { id: titleId, text: 'Indiana testing network' }));
    node.appendChild(svg('desc', {
      id: descId,
      text: 'A map of Indiana showing the test site network: ' +
            NETWORK_IDS.length + ' named testing network locations, plus ' +
            'airports, military installations, ports and university partners ' +
            'for context. Selecting a capability highlights its locations. ' +
            'No testing range boundaries or flight corridors are drawn — none ' +
            'have been published.'
    }));

    var defs = svg('defs');
    defs.appendChild(svg('clipPath', { id: clipId },
      [svg('path', { d: MAP.state })]));

    Object.keys(SYMBOLS).forEach(function (name) {
      defs.appendChild(svg('symbol', {
        id: 'uas-sym-' + name,
        overflow: 'visible',
        html: SYMBOLS[name]
      }));
    });
    node.appendChild(defs);

    /* -- Layer: state fill ------------------------------------------- */
    node.appendChild(svg('path', { 'class': 'uasmap-state-fill', d: MAP.state }));

    /* -- Layer: inside the state (clipped) --------------------------- */
    var inside = svg('g', { 'clip-path': 'url(#' + clipId + ')', 'aria-hidden': 'true' });

    var counties = svg('g', { 'class': 'uasmap-counties' });
    MAP.counties.forEach(function (c) {
      counties.appendChild(svg('path', {
        'class': 'uasmap-county',
        'data-county': c.id,
        d: c.d
      }));
    });
    inside.appendChild(counties);

    /* Monroe County is a named network location but has no marker, being a
       county rather than a site. Its label lives outside the clip so it is
       never cut by the state outline. */
    var countyLabels = svg('g', { 'class': 'uasmap-county-labels' });
    (MAP.networkCounties || []).forEach(function (nc) {
      var geo = MAP.counties.filter(function (c) { return c.id === nc.id; })[0];
      if (!geo || !geo.c) return;
      countyLabels.appendChild(svg('text', {
        'class': 'uasmap-county-label',
        'data-county-label': nc.id,
        x: geo.c[0], y: geo.c[1] + 6,
        'text-anchor': 'middle',
        text: nc.name
      }));
    });

    var water = svg('g', { 'class': 'uasmap-water' });
    MAP.rivers.forEach(function (r) {
      water.appendChild(svg('path', { 'class': 'uasmap-river', d: r.d }));
    });
    inside.appendChild(water);

    var roads = svg('g', { 'class': 'uasmap-roads' });
    MAP.roads.forEach(function (r) {
      roads.appendChild(svg('path', {
        'class': 'uasmap-road uasmap-road-' + r.kind, d: r.d
      }));
    });
    inside.appendChild(roads);

    /* Verified operational geometry. Both collections are empty until the
       test site publishes real boundaries; the loops stay so that adding
       data to site_data.py is all it takes. */
    var ranges = svg('g', { 'class': 'uasmap-ranges' });
    (MAP.ranges || []).forEach(function (r) {
      ranges.appendChild(svg('path', {
        'class': 'uasmap-range' + (r.illustrative ? ' is-illustrative' : ''),
        'data-range': r.id, d: r.d
      }));
    });
    inside.appendChild(ranges);

    var areas = svg('g', { 'class': 'uasmap-areas' });
    (MAP.areas || []).forEach(function (a) {
      areas.appendChild(svg('path', {
        'class': 'uasmap-area' + (a.illustrative ? ' is-illustrative' : ''),
        'data-area': a.id, d: a.d
      }));
    });
    inside.appendChild(areas);

    node.appendChild(inside);

    /* Lake Michigan sits outside the state fill, so it is not clipped. */
    var lakes = svg('g', { 'class': 'uasmap-lakes', 'aria-hidden': 'true' });
    MAP.lakes.forEach(function (l) {
      lakes.appendChild(svg('path', { 'class': 'uasmap-lake', d: l.d }));
    });
    node.appendChild(lakes);

    node.appendChild(svg('path', {
      'class': 'uasmap-state-line', d: MAP.state, 'aria-hidden': 'true'
    }));
    node.appendChild(countyLabels);

    /* Corridors draw over the state line, under the markers. */
    var corridors = svg('g', { 'class': 'uasmap-corridors', 'aria-hidden': 'true' });
    (MAP.corridors || []).forEach(function (c) {
      corridors.appendChild(svg('path', {
        'class': 'uasmap-corridor' + (c.illustrative ? ' is-illustrative' : ''),
        'data-corridor': c.id, d: c.d
      }));
    });
    node.appendChild(corridors);

    /* -- Layer: markers ---------------------------------------------- */
    var markerLayer = svg('g', { 'class': 'uasmap-markers' });
    var markers = {};

    MAP.facilities.forEach(function (f) {
      var label = f.name + (f.network ? ' — testing network location' : '');
      var g = svg('g', {
        'class': 'uasmap-marker uasmap-marker-' + f.type +
                 (f.network ? ' is-network' : '') +
                 (f.outside ? ' is-outside' : ''),
        'data-facility': f.id,
        transform: 'translate(' + f.x + ' ' + f.y + ')',
        tabindex: '0',
        role: 'button',
        'aria-pressed': 'false',
        'aria-label': label
      });

      /* Focus ring as geometry: a browser outline on an SVG group is drawn
         around the untransformed box in several engines, so it cannot be
         relied on to appear in the right place. */
      /* A named network location carries a ring as well as a darker glyph, so
         it is distinguishable without relying on the colour difference. */
      if (f.network) g.appendChild(svg('circle', { 'class': 'uasmap-ring', r: 17 }));
      g.appendChild(svg('circle', { 'class': 'uasmap-focus', r: 21 }));
      g.appendChild(svg('circle', { 'class': 'uasmap-pulse', r: 15 }));
      /* build_map.py sizes each hit area at half the distance to the nearest
         other marker, so no two can overlap however dense the cluster. In the
         densest clusters that is small, which is what the chip list under the
         map is for — and what a touchscreen needs regardless. */
      g.appendChild(svg('circle', { 'class': 'uasmap-hit', r: f.hit || 12 }));
      g.appendChild(svg('use', {
        'class': 'uasmap-glyph',
        href: '#uas-sym-' + symbolFor(f),
        transform: 'scale(' + GLYPH + ')'
      }));

      var text = f.short || f.name;
      var always = f.type === 'city' || f.network;
      var t = svg('text', {
        'class': 'uasmap-label' + (always ? ' is-always' : ''),
        x: 0, y: 0, text: text
      });
      placeLabel(t, f);
      g.appendChild(t);

      markerLayer.appendChild(g);
      markers[f.id] = g;
    });

    node.appendChild(markerLayer);

    return { node: node, markers: markers, counties: counties,
             countyLabels: countyLabels };
  }

  /* Label placement. The default sits to the right of the glyph; a handful
     of markers would collide there, so they are nudged. Keyed by id so the
     exception is visible rather than hidden in a collision solver. */
  var LABEL_POS = {
    'gary': 'below', 'portage': 'right', 'gyy': 'left',
    'gritssom': 'right',
    'lafayette': 'above', 'purdue': 'below',
    'terre-haute': 'below', 'rose-hulman': 'above', 'indiana-state': 'left',
    'huf': 'left', '181iw': 'below',
    'indianapolis': 'above', 'butler': 'left', 'ind': 'left',
    '38id': 'right', '81tc': 'below', 'dfas': 'right',
    'fort-wayne': 'left', 'fwa': 'right', '122fw': 'below',
    'south-bend': 'below', 'sbn': 'above', 'notre-dame': 'right',
    'evansville': 'below', 'evv': 'left',
    'nswc-crane': 'below', 'crane-army': 'above',
    'chicago': 'right', 'ord': 'right',
    'cincinnati': 'left', 'luk': 'left',
    'louisville': 'left', 'sdf': 'left',
    'port-mount-vernon': 'above', 'port-jeffersonville': 'right',
    'port-burns-harbor': 'above'
  };

  function placeLabel(t, f) {
    var pos = LABEL_POS[f.id] || 'right';
    var dx = { right: 19, left: -19, above: 0, below: 0 }[pos];
    var dy = { right: 7, left: 7, above: -18, below: 28 }[pos];
    t.setAttribute('x', dx);
    t.setAttribute('y', dy);
    t.setAttribute('text-anchor',
      pos === 'left' ? 'end' : pos === 'right' ? 'start' : 'middle');
  }

  /* ---------------------------------------------------------------
     Capability navigation — ARIA tabs, vertical
     --------------------------------------------------------------- */
  function buildNav(panelId) {
    var list = el('div', {
      'class': 'cap-nav',
      role: 'tablist',
      'aria-orientation': 'vertical',
      'aria-label': 'Testing capabilities'
    });

    var tabs = [];
    MAP.capabilities.forEach(function (c, i) {
      var tab = el('button', {
        type: 'button',
        'class': 'cap-nav-item',
        id: nextId('cap-tab'),
        role: 'tab',
        'aria-selected': 'false',
        'aria-controls': panelId,
        tabindex: i === 0 ? '0' : '-1',
        'data-capability': c.id
      });

      tab.appendChild(el('span', {
        'class': 'cap-nav-num', 'aria-hidden': 'true',
        text: String(i + 1).padStart(2, '0')
      }));
      tab.appendChild(el('span', { 'class': 'cap-nav-name', text: c.name }));

      if (c.status === 'in-development') {
        tab.appendChild(el('span', {
          'class': 'cap-nav-flag', text: 'In development'
        }));
      }
      /* Shape, not just colour: the selected row grows a caret and an
         accent bar, and announces itself through aria-selected. */
      tab.appendChild(svg('svg', {
        'class': 'cap-nav-caret', viewBox: '0 0 8 12', 'aria-hidden': 'true',
        html: '<path d="M1.5 1 6.5 6l-5 5" fill="none" stroke="currentColor"' +
              ' stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/>'
      }));

      list.appendChild(tab);
      tabs.push(tab);
    });

    list.addEventListener('click', function (e) {
      var t = e.target.closest('.cap-nav-item');
      if (t) set({ capability: t.getAttribute('data-capability'), facility: null });
    });

    list.addEventListener('keydown', function (e) {
      var i = tabs.indexOf(document.activeElement);
      if (i < 0) return;
      var next = null;
      if (e.key === 'ArrowDown' || e.key === 'ArrowRight') next = (i + 1) % tabs.length;
      else if (e.key === 'ArrowUp' || e.key === 'ArrowLeft') next = (i - 1 + tabs.length) % tabs.length;
      else if (e.key === 'Home') next = 0;
      else if (e.key === 'End') next = tabs.length - 1;
      if (next === null) return;
      e.preventDefault();
      tabs[next].focus();
      set({ capability: tabs[next].getAttribute('data-capability'), facility: null });
    });

    return { node: list, tabs: tabs };
  }

  /* ---------------------------------------------------------------
     Detail panel
     --------------------------------------------------------------- */
  function buildPanel(id) {
    return el('div', {
      'class': 'cap-panel',
      id: id,
      role: 'tabpanel',
      tabindex: '0',
      'aria-live': 'polite'
    });
  }

  function renderPanel(panel) {
    panel.textContent = '';

    if (state.facility) return renderFacility(panel, facilityById[state.facility]);
    if (state.capability) return renderCapability(panel, byId[state.capability]);

    panel.appendChild(el('p', {
      'class': 'cap-panel-empty',
      text: 'Select a capability to see where it sits in the testing network, ' +
            'or select a location on the map.'
    }));
  }

  function statusChip(capability) {
    if (capability.status !== 'in-development') return null;
    return el('span', { 'class': 'cap-chip cap-chip-dev', text: 'In development' });
  }

  function renderCapability(panel, c) {
    var resolved = resolve(c);

    panel.appendChild(el('p', { 'class': 'cap-panel-kicker', text: 'Capability' }));

    var head = el('div', { 'class': 'cap-panel-head' });
    head.appendChild(el('h3', { 'class': 'cap-panel-title', text: c.name }));
    var chip = statusChip(c);
    if (chip) head.appendChild(chip);
    panel.appendChild(head);

    if (c.description) {
      panel.appendChild(el('p', { 'class': 'cap-panel-copy', text: c.description }));
    } else {
      panel.appendChild(el('p', { 'class': 'cap-panel-copy', text: c.definition }));
      panel.appendChild(el('p', {
        'class': 'cap-panel-caveat',
        text: 'Defines the capability type. A description of what the test site ' +
              'offers under it has not been published yet.'
      }));
    }

    if (c.status === 'in-development') {
      panel.appendChild(el('p', {
        'class': 'cap-panel-caveat',
        text: 'Not yet operational, and subject to regulatory approval before ' +
              'flight operations begin.'
      }));
    }

    if (resolved.basis === 'service') {
      panel.appendChild(sectionTitle('Delivery'));
      panel.appendChild(el('p', { 'class': 'cap-panel-copy', text: c.service_note }));
      panel.appendChild(contactLink());
      return;
    }

    panel.appendChild(sectionTitle(
      resolved.basis === 'confirmed' ? 'Where it is performed' : 'Testing network'));

    if (resolved.basis === 'pending') {
      panel.appendChild(el('p', {
        'class': 'cap-panel-caveat',
        text: 'The map is showing every location in the testing network. Which ' +
              'of them performs this capability has not been confirmed, so ' +
              'none is singled out here.'
      }));
    }

    var ul = el('ul', { 'class': 'cap-panel-sites' });
    resolved.sites.forEach(function (id) {
      var f = facilityById[id];
      if (!f) return;
      var li = el('li');
      var b = el('button', {
        type: 'button', 'class': 'cap-site-link', 'data-facility': f.id, text: f.name
      });
      li.appendChild(b);
      ul.appendChild(li);
    });
    (resolved.counties || []).forEach(function (id) {
      var meta = (MAP.networkCounties || []).filter(function (c2) { return c2.id === id; })[0];
      if (!meta) return;
      ul.appendChild(el('li', {}, [el('span', { 'class': 'cap-site-static', text: meta.name })]));
    });
    if (ul.childNodes.length) panel.appendChild(ul);

    if (c.id === 'bvlos' && !(MAP.corridors || []).length) {
      panel.appendChild(el('p', {
        'class': 'cap-panel-caveat',
        text: 'No approved corridor geometry has been published, so no flight ' +
              'corridor is drawn on this map.'
      }));
    }

    panel.appendChild(contactLink());
  }

  function renderFacility(panel, f) {
    if (!f) return;

    panel.appendChild(el('p', {
      'class': 'cap-panel-kicker',
      text: f.network ? 'Testing network location' : 'Network context'
    }));

    var head = el('div', { 'class': 'cap-panel-head' });
    head.appendChild(el('h3', { 'class': 'cap-panel-title', text: f.name }));
    panel.appendChild(head);

    if (f.sub) panel.appendChild(el('p', { 'class': 'cap-panel-copy', text: f.sub }));
    if (f.note) panel.appendChild(el('p', { 'class': 'cap-panel-copy', text: f.note }));

    var here = capabilitiesAt(f.id);
    panel.appendChild(sectionTitle('Capabilities at this location'));

    if (here.length) {
      var ul = el('ul', { 'class': 'cap-panel-sites' });
      here.forEach(function (c) {
        var li = el('li');
        li.appendChild(el('button', {
          type: 'button', 'class': 'cap-site-link', 'data-capability': c.id, text: c.name
        }));
        ul.appendChild(li);
      });
      panel.appendChild(ul);
    } else {
      panel.appendChild(el('p', {
        'class': 'cap-panel-caveat',
        text: 'No capability has been assigned to this location yet. Contact the ' +
              'operations team to confirm what can be flown here.'
      }));
    }

    var meta = el('dl', { 'class': 'cap-panel-meta' });
    addMeta(meta, 'Coordinates', f.lat.toFixed(4) + '°N, ' +
      Math.abs(f.lon).toFixed(4) + '°W');
    addMeta(meta, 'Source', f.precision === 'dataset'
      ? f.source
      : 'Site centroid, approximate');
    if (f.displaced) {
      addMeta(meta, 'Marker', 'Nudged apart from a neighbouring marker so both ' +
        'stay readable. The coordinates above are as sourced.');
    }
    panel.appendChild(meta);

    if (f.url) {
      var a = el('a', {
        'class': 'link-arrow cap-panel-link',
        href: f.url, target: '_blank', rel: 'noopener noreferrer'
      });
      a.appendChild(document.createTextNode(f.name));
      a.appendChild(el('span', { 'class': 'sr-only', text: ' (opens in a new tab)' }));
      panel.appendChild(el('p', {}, [a]));
    }

    panel.appendChild(contactLink());
  }

  function addMeta(dl, term, value) {
    dl.appendChild(el('dt', { text: term }));
    dl.appendChild(el('dd', { text: value }));
  }

  function sectionTitle(text) {
    return el('h4', { 'class': 'cap-panel-subtitle', text: text });
  }

  function contactLink() {
    return el('p', { 'class': 'cap-panel-cta' }, [
      el('a', { 'class': 'link-arrow', href: '/#contact', text: 'Discuss this with the operations team' })
    ]);
  }

  /* ---------------------------------------------------------------
     Location list
     ---------------------------------------------------------------
     The map is dense enough that a marker is a small target, and on a
     phone it is a very small one. This is the same selection by another
     route: real buttons, full size, keyboard and screen-reader native,
     and no hovering anywhere in it. The named network locations are up
     front; the rest of the network is one disclosure away. */
  var TYPE_LABEL = {
    military: 'Military installations', airport: 'Airports',
    university: 'Universities', port: 'Ports of Indiana',
    city: 'Cities', agency: 'Federal agencies'
  };

  function buildLocations() {
    var box = el('div', { 'class': 'cap-locations' });
    box.appendChild(el('h3', { 'class': 'cap-legend-title', text: 'Select a location' }));

    var top = el('ul', { 'class': 'cap-panel-sites cap-locations-top' });
    MAP.facilities.filter(function (f) { return f.network; }).forEach(function (f) {
      top.appendChild(el('li', {}, [el('button', {
        type: 'button', 'class': 'cap-site-link', 'data-facility': f.id, text: f.name
      })]));
    });
    (MAP.networkCounties || []).forEach(function (c) {
      top.appendChild(el('li', {}, [el('span', { 'class': 'cap-site-static', text: c.name })]));
    });
    box.appendChild(top);

    var rest = el('details', { 'class': 'cap-locations-more' });
    rest.appendChild(el('summary', { text: 'All mapped locations' }));

    Object.keys(TYPE_LABEL).forEach(function (type) {
      var items = MAP.facilities.filter(function (f) {
        return f.type === type && !f.network;
      });
      if (!items.length) return;
      rest.appendChild(el('h4', { 'class': 'cap-locations-group', text: TYPE_LABEL[type] }));
      var ul = el('ul', { 'class': 'cap-panel-sites' });
      items.forEach(function (f) {
        ul.appendChild(el('li', {}, [el('button', {
          type: 'button', 'class': 'cap-site-link', 'data-facility': f.id,
          text: f.short ? f.short + ' — ' + f.name : f.name
        })]));
      });
      rest.appendChild(ul);
    });

    box.appendChild(rest);
    return box;
  }

  /* ---------------------------------------------------------------
     Legend
     ---------------------------------------------------------------
     States what each mark means, and — just as importantly — says out
     loud which layers carry no data, so an empty map is read as "not
     published" rather than "nothing here". */
  function buildLegend() {
    var box = el('div', { 'class': 'cap-legend' });
    box.appendChild(el('h3', { 'class': 'cap-legend-title', text: 'Legend' }));

    var list = el('ul', { 'class': 'cap-legend-list' });

    function entry(symbolName, label, modifier) {
      var li = el('li', { 'class': 'cap-legend-item' + (modifier ? ' ' + modifier : '') });
      var mark = svg('svg', { 'class': 'cap-legend-mark', viewBox: '-9 -9 18 18',
        'aria-hidden': 'true', html: SYMBOLS[symbolName] });
      li.appendChild(mark);
      li.appendChild(el('span', { text: label }));
      list.appendChild(li);
    }

    function lineEntry(cls, label) {
      var li = el('li', { 'class': 'cap-legend-item' });
      li.appendChild(svg('svg', { 'class': 'cap-legend-mark', viewBox: '-9 -9 18 18',
        'aria-hidden': 'true',
        html: '<path class="' + cls + '" d="M-8 0H8" fill="none"/>' }));
      li.appendChild(el('span', { text: label }));
      list.appendChild(li);
    }

    entry('military', 'Military installation');
    entry('airport', 'Airport');
    entry('university', 'University');
    entry('port', 'Port of Indiana');
    entry('capital', 'State capital');
    entry('city', 'City');
    lineEntry('uasmap-road uasmap-road-interstate', 'Interstate');
    lineEntry('uasmap-river', 'River');

    box.appendChild(list);

    box.appendChild(el('p', {
      'class': 'cap-legend-note',
      text: 'A heavier ring marks one of the ' + NETWORK_IDS.length +
            ' named testing network locations plus Monroe County.'
    }));

    var missing = [];
    if (!(MAP.ranges || []).length) missing.push('testing range boundaries');
    if (!(MAP.corridors || []).length) missing.push('BVLOS flight corridors');
    if (missing.length) {
      box.appendChild(el('p', {
        'class': 'cap-legend-note cap-legend-absent',
        text: 'Not drawn: ' + missing.join(' and ') + '. No approved geometry has ' +
              'been published, and none is estimated here.'
      }));
    }

    box.appendChild(el('p', {
      'class': 'cap-legend-note',
      text: 'Boundaries: US Census cartographic files. Roads and water: Natural ' +
            'Earth. Airports: OurAirports. Campus and installation markers are ' +
            'site centroids.'
    }));

    return box;
  }

  /* ---------------------------------------------------------------
     Assemble
     --------------------------------------------------------------- */
  var panelId = nextId('cap-panel');
  var nav = buildNav(panelId);
  var panel = buildPanel(panelId);
  var map = buildMap();
  var legend = buildLegend();
  var locations = buildLocations();

  var layout = el('div', { 'class': 'cap-explorer-grid' });

  /* The panel sits under the navigation rather than under the map: it is what
     the navigation controls, so it belongs next to it in reading order, and
     the column is tall enough to hold it without the map growing. */
  var left = el('div', { 'class': 'cap-explorer-nav' });
  left.appendChild(nav.node);
  left.appendChild(panel);

  var right = el('div', { 'class': 'cap-explorer-map' });
  var figure = el('figure', { 'class': 'cap-map-figure' });
  figure.appendChild(map.node);
  right.appendChild(figure);
  right.appendChild(locations);
  right.appendChild(legend);

  layout.appendChild(left);
  layout.appendChild(right);

  var shell = el('div', { 'class': 'cap-explorer is-live' });
  shell.appendChild(layout);

  /* Swap the static list out only once the replacement is built, so a
     throw above this line leaves the page as it was. */
  var staticList = root.querySelector('.cap-list');
  if (staticList) staticList.hidden = true;
  var staticNote = root.querySelector('.cap-list-note');
  root.insertBefore(shell, staticNote || null);

  /* Reverse interaction: a marker selects its facility. */
  map.node.addEventListener('click', function (e) {
    var g = e.target.closest('.uasmap-marker');
    if (g) set({ facility: g.getAttribute('data-facility') });
  });

  map.node.addEventListener('keydown', function (e) {
    if (e.key !== 'Enter' && e.key !== ' ' && e.key !== 'Spacebar') return;
    var g = e.target.closest('.uasmap-marker');
    if (!g) return;
    e.preventDefault();
    set({ facility: g.getAttribute('data-facility') });
  });

  /* Panel and location-list cross-links, both directions. */
  function onChipClick(e) {
    var b = e.target.closest('button[data-facility], button[data-capability]');
    if (!b) return;
    if (b.hasAttribute('data-facility')) {
      set({ facility: b.getAttribute('data-facility') });
    } else {
      selectCapability(b.getAttribute('data-capability'), true);
    }
  }
  panel.addEventListener('click', onChipClick);
  locations.addEventListener('click', onChipClick);

  function selectCapability(id, focusTab) {
    set({ capability: id, facility: null });
    if (!focusTab) return;
    nav.tabs.forEach(function (t) {
      if (t.getAttribute('data-capability') === id) t.focus();
    });
  }

  /* ---------------------------------------------------------------
     One render pass
     --------------------------------------------------------------- */
  function apply() {
    var capability = state.capability ? byId[state.capability] : null;
    var resolved = resolve(capability);

    nav.tabs.forEach(function (t) {
      var on = t.getAttribute('data-capability') === state.capability;
      t.setAttribute('aria-selected', String(on));
      t.classList.toggle('is-active', on);
      t.tabIndex = on ? 0 : -1;
    });
    if (!state.capability && nav.tabs.length) nav.tabs[0].tabIndex = 0;

    var highlighted = {};
    resolved.sites.forEach(function (id) { highlighted[id] = true; });

    var dimming = resolved.basis === 'confirmed' || resolved.basis === 'pending';
    map.node.classList.toggle('is-dimmed', dimming);
    map.node.classList.toggle('is-service', resolved.basis === 'service');

    Object.keys(map.markers).forEach(function (id) {
      var g = map.markers[id];
      var on = !!highlighted[id];
      var selected = state.facility === id;
      g.classList.toggle('is-highlighted', on);
      g.classList.toggle('is-selected', selected);
      g.setAttribute('aria-pressed', String(selected));
    });

    var counties = {};
    (resolved.counties || []).forEach(function (id) { counties[id] = true; });
    Array.prototype.forEach.call(
      map.counties.querySelectorAll('.uasmap-county'), function (p) {
        p.classList.toggle('is-highlighted', !!counties[p.getAttribute('data-county')]);
      });
    Array.prototype.forEach.call(
      map.countyLabels.querySelectorAll('.uasmap-county-label'), function (t) {
        t.classList.toggle('is-visible', !!counties[t.getAttribute('data-county-label')]);
      });

    /* The chip list mirrors the map's state, so the selection is visible
       wherever the visitor is working — and without needing to hover. */
    Array.prototype.forEach.call(
      locations.querySelectorAll('button[data-facility]'), function (b) {
        var id = b.getAttribute('data-facility');
        b.classList.toggle('is-selected', state.facility === id);
        b.classList.toggle('is-highlighted', !!highlighted[id]);
        b.setAttribute('aria-pressed', String(state.facility === id));
      });

    renderPanel(panel);
  }

  listeners.push(apply);
  apply();
})();
